import { createHash } from 'node:crypto';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';

const CATEGORY = 'Category:HeartGold and SoulSilver Shiny sprites';
const API_URL = 'https://archives.bulbagarden.net/w/api.php';
const OUTPUT_DIR = path.resolve('public/img/game-sprites/hgss');
const MANIFEST_PATH = path.resolve('src/data/hgss-shiny-sprite-manifest.ts');
const USER_AGENT = 'PokeShinyTracker sprite archive builder (https://github.com/Cosmi4002/pokeshinytracker)';

const sleep = (ms) => new Promise((resolve) => setTimeout(resolve, ms));
const normalizeFilename = (title) => title.replace(/^File:/, '').replaceAll(' ', '_');

async function fetchCategoryFiles() {
  const files = [];
  let continuation = null;

  do {
    const url = new URL(API_URL);
    url.searchParams.set('action', 'query');
    url.searchParams.set('generator', 'categorymembers');
    url.searchParams.set('gcmtitle', CATEGORY);
    url.searchParams.set('gcmtype', 'file');
    url.searchParams.set('gcmlimit', 'max');
    url.searchParams.set('prop', 'imageinfo');
    url.searchParams.set('iiprop', 'url|size|mime');
    url.searchParams.set('format', 'json');
    url.searchParams.set('formatversion', '2');
    if (continuation) url.searchParams.set('gcmcontinue', continuation);

    const response = await fetch(url, { headers: { 'User-Agent': USER_AGENT } });
    if (!response.ok) throw new Error(`Category request failed: ${response.status}`);
    const payload = await response.json();
    for (const page of payload.query?.pages || []) {
      const info = page.imageinfo?.[0];
      if (!info?.url || info.mime !== 'image/png') continue;
      files.push({
        filename: normalizeFilename(page.title),
        sourceUrl: info.url,
        sourceSize: info.size,
      });
    }
    continuation = payload.continue?.gcmcontinue || null;
    if (continuation) await sleep(250);
  } while (continuation);

  return files.sort((a, b) => a.filename.localeCompare(b.filename, 'en', { numeric: true }));
}

async function downloadFile(file) {
  const destination = path.join(OUTPUT_DIR, file.filename);
  try {
    const existing = await readFile(destination);
    if (existing.byteLength === file.sourceSize) return existing;
  } catch {
    // Missing or incomplete file: download it below.
  }

  const response = await fetch(file.sourceUrl, { headers: { 'User-Agent': USER_AGENT } });
  if (!response.ok) throw new Error(`Sprite request failed (${response.status}): ${file.sourceUrl}`);
  const bytes = Buffer.from(await response.arrayBuffer());
  await writeFile(destination, bytes);
  await sleep(40);
  return bytes;
}

async function runPool(items, concurrency, worker) {
  let cursor = 0;
  const workers = Array.from({ length: concurrency }, async () => {
    while (cursor < items.length) {
      const index = cursor++;
      await worker(items[index], index);
    }
  });
  await Promise.all(workers);
}

await mkdir(OUTPUT_DIR, { recursive: true });
const files = await fetchCategoryFiles();
const manifest = [];

await runPool(files, 6, async (file, index) => {
  const bytes = await downloadFile(file);
  manifest[index] = {
    filename: file.filename,
    bytes: bytes.byteLength,
    sha256: createHash('sha256').update(bytes).digest('hex'),
  };
  if ((index + 1) % 50 === 0 || index + 1 === files.length) {
    process.stdout.write(`Downloaded ${index + 1}/${files.length}\n`);
  }
});

const generated = `// Generated by scripts/download-hgss-shiny-sprites.mjs.\n` +
  `// Source: ${CATEGORY}, Bulbagarden Archives.\n` +
  `export const HGSS_SHINY_SPRITE_FILES = ${JSON.stringify(manifest.map((item) => item.filename), null, 2)} as const;\n`;

await mkdir(path.dirname(MANIFEST_PATH), { recursive: true });
await writeFile(MANIFEST_PATH, generated);
await writeFile(path.join(OUTPUT_DIR, 'manifest.json'), JSON.stringify({
  set: 'hgss',
  games: ['heartgold', 'soulsilver'],
  source: `https://archives.bulbagarden.net/wiki/${CATEGORY.replaceAll(' ', '_')}`,
  files: manifest,
}, null, 2));

const totalBytes = manifest.reduce((sum, item) => sum + item.bytes, 0);
process.stdout.write(`HGSS archive ready: ${manifest.length} APNG files, ${(totalBytes / 1024 / 1024).toFixed(2)} MiB\n`);
