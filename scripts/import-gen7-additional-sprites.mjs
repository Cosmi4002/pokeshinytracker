import { mkdir, readFile, rm, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { execFileSync } from 'node:child_process';
import sharp from 'sharp';

const root = path.resolve('.');
const archive = path.join(root, 'gen7additionals.zip');
const tempDir = path.join(root, `.sprite-import-gen7-additional-${process.pid}`);
const outputDir = path.join(root, 'public/img/game-sprites/gen6-7');
const manifestPath = path.join(root, 'src/data/gen7-additional-shiny-sprite-manifest.ts');
const reportPath = path.join(root, 'reports/gen7-additional-sprite-import.json');
const catalogPath = path.join(root, 'src/lib/pokemon-catalog-v2.generated.json');

const aliases = {
  blacephalon: 'blacephalon',
  'mimikyu': 'mimikyu-disguised',
  naganadel: 'naganadel',
  'pikachu-partnercap': 'pikachu-partner-cap',
  poipole: 'poipole',
  stakataka: 'stakataka',
  'tapu-bulu': 'tapu-bulu',
  'tapu-fini': 'tapu-fini',
  'tapu-koko': 'tapu-koko',
  'tapu-lele': 'tapu-lele',
  tapubulu: 'tapu-bulu',
  tapufini: 'tapu-fini',
  tapukoko: 'tapu-koko',
  tapulele: 'tapu-lele',
  'type-null': 'type-null',
  typenull: 'type-null',
  'lycanroc-dusk': 'lycanroc-dusk',
  'oricorio-bayle': 'oricorio-baile',
  'oricorio-pompom': 'oricorio-pom-pom',
  zeraora: 'zeraora',
};

const normalize = value => value
  .normalize('NFKD')
  .replace(/[\u0300-\u036f]/g, '')
  .toLowerCase()
  .replace(/_/g, '-')
  .replace(/[^a-z0-9-]+/g, '-')
  .replace(/-+/g, '-')
  .replace(/^-|-$/g, '');

const readJson = file => readFile(file, 'utf8').then(JSON.parse);
const assetSlug = filename => normalize(filename
  .replace(/\.(?:gif|webp)$/i, '')
  .replace(/[_-]usum$/i, ''));

await rm(tempDir, { recursive: true, force: true }).catch(() => {});
await mkdir(tempDir, { recursive: true });
await mkdir(outputDir, { recursive: true });
execFileSync('tar', ['-xf', archive, '-C', tempDir]);

const catalog = await readJson(catalogPath);
const entitiesByName = new Map();
for (const entity of catalog) {
  for (const name of [entity.canonicalName, ...(entity.legacy?.formNames || []), ...(entity.legacy?.displayNames || [])]) {
    entitiesByName.set(normalize(name), entity);
  }
}

const archiveFiles = execFileSync('tar', ['-tf', archive], { encoding: 'utf8' })
  .split(/\r?\n/)
  .filter(filename => /\.(?:gif|webp)$/i.test(filename));
const entries = [];
const unresolved = [];

for (const archiveName of archiveFiles) {
  const filename = path.basename(archiveName);
  const usumOnly = /_usum\.(?:gif|webp)$/i.test(filename);
  const slug = aliases[assetSlug(filename)] || assetSlug(filename);
  const entity = entitiesByName.get(slug);
  if (!entity) {
    unresolved.push(filename);
    continue;
  }

  const outputName = `${normalize(entity.canonicalName)}${usumOnly ? '-usum' : ''}.webp`;
  await sharp(path.join(tempDir, archiveName), { animated: true })
    .webp({ lossless: true, effort: 6 })
    .toFile(path.join(outputDir, outputName));

  entries.push({
    file: outputName,
    source: filename,
    speciesId: entity.speciesId,
    canonicalName: entity.canonicalName,
    games: usumOnly ? ['ultrasun', 'ultramoon'] : ['sun', 'moon', 'ultrasun', 'ultramoon'],
  });
}

await writeFile(manifestPath, `// Generated by scripts/import-gen7-additional-sprites.mjs.\nexport const GEN7_ADDITIONAL_SHINY_SPRITE_ENTRIES = ${JSON.stringify(entries, null, 2)} as const;\n`);
await writeFile(reportPath, JSON.stringify({ archive, files: archiveFiles.length, imported: entries.length, unresolved }, null, 2));
await rm(tempDir, { recursive: true, force: true, maxRetries: 5, retryDelay: 250 }).catch(() => {});
console.log(JSON.stringify({ files: archiveFiles.length, imported: entries.length, unresolved: unresolved.length, report: reportPath }, null, 2));