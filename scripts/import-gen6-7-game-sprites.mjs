import { mkdir, readFile, rm, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { execFileSync } from 'node:child_process';
import sharp from 'sharp';

const root = path.resolve('.');
const archive = path.join(root, 'xyorassmusumnotall.zip');
const tempDir = path.join(root, `.sprite-import-tmp-${process.pid}`);
const outputDir = path.join(root, 'public/img/game-sprites/gen6-7');
const manifestPath = path.join(root, 'src/data/gen6-7-shiny-sprite-manifest.ts');
const reportPath = path.join(root, 'reports/gen6-7-sprite-import.json');
const catalogPath = path.join(root, 'src/lib/pokemon-catalog-v2.generated.json');
const pokedexPath = path.join(root, 'src/lib/pokedex.json');

const explicitAliases = {
  basculin: 'basculin-red-striped',
  'basculin-blue': 'basculin-blue-striped',
  burmy: 'burmy-plant',
  deerling: 'deerling-spring',
  deoxys: 'deoxys-normal',
  'flabebe-red': 'flabebe',
  'floette-red': 'floette',
  'florges-red': 'florges',
  giratina: 'giratina-altered',
  gourgeist: 'gourgeist-average',
  keldeo: 'keldeo-ordinary',
  landorus: 'landorus-incarnate',
  meloetta: 'meloetta-aria',
  meowstic: 'meowstic-male',
  nidoran: 'nidoran-f',
  pumpkaboo: 'pumpkaboo-average',
  sawsbuck: 'sawsbuck-spring',
  shaymin: 'shaymin-land',
  thundurus: 'thundurus-incarnate',
  tornadus: 'tornadus-incarnate',
  'vivillon-highplains': 'vivillon-high-plains',
  'vivillon-savannah': 'vivillon-savanna',
  wormadam: 'wormadam-plant',
  zygarde: 'zygarde-50',
  'nidoran_f': 'nidoran-f',
  'nidoran_m': 'nidoran-m',
};

const excludedFiles = new Set(['mawile-mega.gif', 'floette-eternal.gif']);

const normalize = value => value
  .normalize('NFKD')
  .replace(/[\u0300-\u036f]/g, '')
  .toLowerCase()
  .replace(/_/g, '-')
  .replace(/[^a-z0-9-]+/g, '-')
  .replace(/-+/g, '-')
  .replace(/^-|-$/g, '');

const fileSlug = filename => normalize(filename.replace(/\.gif$/i, ''));
const readJson = file => readFile(file, 'utf8').then(JSON.parse);

await rm(tempDir, { recursive: true, force: true }).catch(() => {});
await mkdir(tempDir, { recursive: true });
await mkdir(outputDir, { recursive: true });
execFileSync('tar', ['-xf', archive, '-C', tempDir]);

const [pokedex, catalog] = await Promise.all([readJson(pokedexPath), readJson(catalogPath)]);
const idsByName = new Map(pokedex.map(entry => [normalize(entry.name), entry.id]));
const entitiesByName = new Map();
for (const entity of catalog) {
  for (const name of [entity.canonicalName, ...(entity.legacy?.formNames || []), ...(entity.legacy?.displayNames || [])]) {
    entitiesByName.set(normalize(name), entity);
  }
}

const resolveEntity = slug => {
  const canonicalSlug = explicitAliases[slug] || slug;
  const direct = entitiesByName.get(canonicalSlug);
  if (direct) return { entity: direct, canonicalName: direct.canonicalName };
  const id = idsByName.get(canonicalSlug);
  if (id) return { entity: { speciesId: id, canonicalName: canonicalSlug }, canonicalName: canonicalSlug };
  const baseName = canonicalSlug.split('-')[0];
  const baseId = idsByName.get(baseName);
  if (!baseId) return null;
  const matching = [...entitiesByName.values()].find(entity =>
    entity.speciesId === baseId && normalize(entity.canonicalName) === canonicalSlug,
  );
  return matching ? { entity: matching, canonicalName: matching.canonicalName } : null;
};

const gifFiles = (await readFile(path.join(tempDir, '0-credits.txt')).catch(() => '')) &&
  execFileSync('tar', ['-tf', archive], { encoding: 'utf8' })
    .split(/\r?\n/)
    .filter(filename => filename.toLowerCase().endsWith('.gif'));
const entries = [];
const unresolved = [];
const ignored = [];

for (const archiveName of gifFiles) {
  if (excludedFiles.has(archiveName)) {
    ignored.push(archiveName);
    continue;
  }
  const slug = fileSlug(archiveName);
  const gender = slug.endsWith('-f') ? 'female' : 'male';
  const lookupSlug = gender === 'female' ? slug.slice(0, -2) : slug;
  const resolved = resolveEntity(lookupSlug);
  if (!resolved) {
    unresolved.push(archiveName);
    continue;
  }
  const outputName = `${normalize(resolved.canonicalName)}${gender === 'female' ? '-f' : ''}.webp`;
  const source = path.join(tempDir, archiveName);
  await sharp(source, { animated: true })
    .webp({ lossless: true, effort: 4 })
    .toFile(path.join(outputDir, outputName));
  entries.push({
    file: outputName,
    source: archiveName,
    speciesId: resolved.entity.speciesId,
    canonicalName: resolved.canonicalName,
    gender,
  });
}

await writeFile(manifestPath, `// Generated by scripts/import-gen6-7-game-sprites.mjs.\nexport const GEN6_7_SHINY_SPRITE_ENTRIES = ${JSON.stringify(entries, null, 2)} as const;\n`);
await writeFile(reportPath, JSON.stringify({ archive, files: gifFiles.length, imported: entries.length, ignored, unresolved }, null, 2));
await rm(tempDir, { recursive: true, force: true, maxRetries: 5, retryDelay: 250 }).catch(() => {
  console.warn(`Temporary import directory could not be removed yet: ${tempDir}`);
});
console.log(JSON.stringify({ files: gifFiles.length, imported: entries.length, ignored: ignored.length, unresolved: unresolved.length, report: reportPath }, null, 2));